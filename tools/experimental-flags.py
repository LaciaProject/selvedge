#!/usr/bin/env python3
"""Lists workerd's experimental compatibility flags, which tenants may not use.

Usage: tools/experimental-flags.py <workerd version> > crates/selvedge-workerd/src/experimental-flags.txt

Reads src/workerd/io/compatibility-date.capnp at that release tag and prints
every enable and disable flag of a field annotated `$experimental`.
"""
import re, sys, urllib.request

version = sys.argv[1]
url = f"https://raw.githubusercontent.com/cloudflare/workerd/v{version}/src/workerd/io/compatibility-date.capnp"
text = urllib.request.urlopen(url).read().decode()
print(f"# workerd {version}: experimental compatibility flags. Generated by tools/experimental-flags.py.")
for name, annotations in re.findall(r"(\w+)\s+@\d+\s*:Bool([^;]*);", text):
    if "$experimental" in annotations:
        for flag in re.findall(r'\$compat(?:Enable|Disable)Flag\("([^"]+)"\)', annotations):
            print(flag)
